"""Fine-tune the YOLO nano model on CPU within a small, stated budget.

    python -m vision.train                # default budget
    python -m vision.train --epochs 3     # quicker, worse

Budget (defaults): YOLO11n pretrained weights, 800 training images, image size 320,
12 epochs, batch 16, CPU only. The validation metrics of the run are written to
docs/vision_training_results.md exactly as Ultralytics reports them.

The pretrained weights (about 5 MB) are downloaded by Ultralytics from its public
release page the first time; no account is needed.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from backend.config import PROJECT_ROOT, settings
from vision.dataset import TARGET

BASE_WEIGHTS = "yolo11n.pt"


def main() -> int:
    parser = argparse.ArgumentParser(prog="python -m vision.train", description=__doc__.split("\n\n")[0])
    parser.add_argument("--epochs", type=int, default=12)
    parser.add_argument("--imgsz", type=int, default=320)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    data_yaml = TARGET / "data.yaml"
    if not data_yaml.exists():
        print(f"No dataset at {data_yaml}. Run:  python scripts/download_dataset.py  then  python -m vision.dataset", file=sys.stderr)
        return 1

    import torch
    import ultralytics
    from ultralytics import YOLO

    train_images = len(list((TARGET / "images" / "train").glob("*.jpg")))
    val_images = len(list((TARGET / "images" / "val").glob("*.jpg")))
    runs = settings.data_dir / "vision_runs"
    base = settings.vision_weights.parent / BASE_WEIGHTS
    base.parent.mkdir(parents=True, exist_ok=True)

    print(f"Fine-tuning {BASE_WEIGHTS}: {train_images} train / {val_images} val images, imgsz {args.imgsz}, "
          f"{args.epochs} epochs, batch {args.batch}, CPU ({torch.get_num_threads()} threads)")
    started = time.monotonic()
    model = YOLO(str(base))  # downloads to vision/models/ if absent
    model.train(
        data=str(data_yaml), epochs=args.epochs, imgsz=args.imgsz, batch=args.batch, device="cpu", workers=0,
        seed=args.seed, project=str(runs), name="crack", exist_ok=True, plots=False, verbose=False, patience=100,
    )
    minutes = (time.monotonic() - started) / 60.0

    best = runs / "crack" / "weights" / "best.pt"
    if not best.exists():
        print(f"Training finished but {best} is missing.", file=sys.stderr)
        return 1
    settings.vision_weights.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(best, settings.vision_weights)

    metrics = YOLO(str(settings.vision_weights)).val(
        data=str(data_yaml), imgsz=args.imgsz, batch=args.batch, device="cpu", workers=0, plots=False, verbose=False,
        project=str(runs), name="crack_val", exist_ok=True,
    )
    results = {
        "precision": float(metrics.box.mp),
        "recall": float(metrics.box.mr),
        "mAP50": float(metrics.box.map50),
        "mAP50-95": float(metrics.box.map),
    }

    size_mb = settings.vision_weights.stat().st_size / 1e6
    report = f"""# Vision model training results

Generated by `python -m vision.train` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M')} UTC.

**What this model is.** A YOLO11n detector fine-tuned on a subset of the public crack-seg
dataset (cracks in roads and walls). It is a prototype crack detector. It has not been
trained or tested on conveyor-belt images, and these numbers say nothing about how it
would perform on a belt.

## Budget

| Setting | Value |
|---|---|
| Base weights | {BASE_WEIGHTS} (pretrained, Ultralytics {ultralytics.__version__}) |
| Training images | {train_images} (seeded subset of the 3,717 in the published train split) |
| Validation images | {val_images} (the whole published validation split) |
| Labels | bounding boxes computed from the dataset's segmentation polygons |
| Preprocessing | bilateral denoise + CLAHE, same as at inference |
| Image size | {args.imgsz} |
| Epochs | {args.epochs} |
| Batch size | {args.batch} |
| Device | CPU, {torch.get_num_threads()} threads (torch {torch.__version__}) |
| Wall time | {minutes:.1f} minutes |
| Weights file | {size_mb:.1f} MB |

## Validation metrics (class: crack)

| Metric | Value |
|---|---|
| Precision | {results['precision']:.3f} |
| Recall | {results['recall']:.3f} |
| mAP@0.5 | {results['mAP50']:.3f} |
| mAP@0.5:0.95 | {results['mAP50-95']:.3f} |

Measured by Ultralytics' validator on the validation images at image size {args.imgsz}.

## Limits

- Small budget: a subset of the data, a small image size and few epochs, chosen to finish
  on a laptop CPU. More epochs and the full training split would raise these numbers.
- Boxes around thin diagonal cracks are mostly background, which makes box overlap a
  harsh measure for this kind of defect; the dataset's own task is segmentation.
- The validation images come from the same source as the training images. The numbers do
  not measure how the model transfers to a different surface such as belt rubber.
"""
    out = PROJECT_ROOT / "docs" / "vision_training_results.md"
    out.write_text(report, encoding="utf-8")
    print(f"\nValidation: " + ", ".join(f"{k} {v:.3f}" for k, v in results.items()))
    print(f"Training took {minutes:.1f} minutes. Weights: {settings.vision_weights} ({size_mb:.1f} MB). Report: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
